export interface Course {
  /** 산 이름 (예: '북한산') */
  mountain: string;
  /** 코스 이름 (예: '우이동 - 백운대') */
  name: string;
  /** 편도 거리 (km) */
  km: number;
  /** 누적 상승고도 (m). 자료가 없으면 정상 표고 − 들머리 표고로 추정하고 note에 '추정' 표기 */
  gain: number;
  /** 공식 안내 기준 편도 소요시간 (분). 없으면 null */
  officialMinutes: number | null;
  /** 난이도 — 공식 표기가 있으면 그대로 */
  level: '쉬움' | '보통' | '어려움';
  /** 지역 (예: '서울') */
  region: string;
  note?: string;
}

/**
 * 거리와 누적고도로 소요시간(분)을 추정.
 * Langmuir 단체 보정 네이스미스 법칙: 평지 4km/h + 상승 450m당 1시간.
 * fitness는 체력 계수(0.8 빠름 ~ 1.3 느림).
 *
 * ⚠ gain이 음수(-1 = 미확인)면 **NaN을 반환한다.** 이 데이터셋의 상당수 코스는
 *   누적고도를 확보하지 못했고, -1을 그대로 계산에 넣으면 조용히 평지 보행
 *   시간에 가까운 엉뚱한 값이 나온다(예: 지리산 중산리 10.8km/-1 → 162분,
 *   실제 공식 480분). 그래서 조용히 틀리는 대신 NaN으로 터뜨린다.
 *   호출부에서 Number.isNaN()으로 걸러 공식 시간(officialMinutes)만 노출할 것.
 */
export function estimateMinutes(km: number, gain: number, fitness: number): number {
  if (!(km >= 0) || !(gain >= 0) || !(fitness > 0)) return NaN;
  const flatMinutes = (km / 4) * 60;
  const climbMinutes = (gain / 450) * 60;
  return Math.round((flatMinutes + climbMinutes) * fitness);
}

